"""Docs generator: one Markdown page per contract and a mermaid graph of the pipeline."""

from __future__ import annotations

import re
from pathlib import Path

from .contract import Contract, load_dir


def _node(name: str) -> str:
    """A mermaid node id: letters, digits and underscores only."""
    return "n_" + re.sub(r"\W", "_", name)


def _label(text: str) -> str:
    """A quoted mermaid label. Quotes, brackets and pipes become HTML entities."""
    for ch, ent in (('"', "#quot;"), ("|", "#124;"), ("[", "#91;"), ("]", "#93;")):
        text = text.replace(ch, ent)
    return f'"{text}"'


def mermaid(contracts: list[Contract]) -> str:
    lines = ["flowchart LR"]
    nodes = []
    for c in contracts:
        for n in (c.producer, c.consumer):
            if n not in nodes:
                nodes.append(n)
    for n in nodes:
        lines.append(f"  {_node(n)}[{_label(n)}]")
    for c in contracts:
        lines.append(f"  {_node(c.producer)} -->|{_label(c.name)}| {_node(c.consumer)}")
    return "\n".join(lines)


def _rules(spec) -> str:
    parts = []
    if spec.enum is not None:
        parts.append("one of " + ", ".join(f"`{e}`" for e in spec.enum))
    if spec.min_length is not None or spec.max_length is not None:
        parts.append(f"length {spec.min_length or 0} to {spec.max_length or 'any'}")
    if spec.min_items is not None or spec.max_items is not None:
        parts.append(f"items {spec.min_items or 0} to {spec.max_items or 'any'}")
    if spec.ref:
        parts.append(f"must exist at context `{spec.ref}`")
    return ", ".join(parts) or "none"


def page(c: Contract) -> str:
    out = [
        f"# Contract `{c.name}`",
        "",
        f"Producer: `{c.producer}`. Consumer: `{c.consumer}`. Source: `{c.source}`.",
        "",
    ]
    if c.description:
        out += [c.description, ""]
    out += [
        "Unknown fields: " + ("rejected." if c.extra == "forbid" else "allowed."),
        "",
        "| Field | Type | Required | Rules |",
        "| --- | --- | --- | --- |",
    ]
    for f in c.fields.values():
        rules = _rules(f).replace("|", "\\|")
        out.append(f"| `{f.name}` | `{f.type}` | {'yes' if f.required else 'no'} | {rules} |")
    out += ["", "Semantic checks:", ""]
    out += [f"- `{s}`" for s in c.semantic] or ["- none"]
    out += ["", "[Back to the graph](README.md)", ""]
    return "\n".join(out)


def generate(
    contracts_dir: str | Path, out_dir: str | Path, order: list[str] | None = None
) -> list[Path]:
    cs = load_dir(contracts_dir)
    names = order or sorted(cs)
    contracts = [cs[n] for n in names]
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for c in contracts:
        p = out / f"{c.name}.md"
        p.write_text(page(c), encoding="utf-8")
        written.append(p)
    index = [
        "# Contracts",
        "",
        "This page is generated by `handoffpact docs`. Each arrow is one handoff with its contract.",
        "",
        "```mermaid",
        mermaid(contracts),
        "```",
        "",
        "| Edge | Producer | Consumer | Fields | Semantic checks |",
        "| --- | --- | --- | --- | --- |",
    ]
    for c in contracts:
        index.append(
            f"| [{c.name}]({c.name}.md) | `{c.producer}` | `{c.consumer}` | {len(c.fields)} | {len(c.semantic)} |"
        )
    p = out / "README.md"
    p.write_text("\n".join(index) + "\n", encoding="utf-8")
    written.append(p)
    return written
